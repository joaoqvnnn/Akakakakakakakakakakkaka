window.fillBanksSelect = function (selectEl, selectedCode) {
  const sorted = [...window.BANKS_BR].sort((a, b) => a.name.localeCompare(b.name, "pt-BR"));
  selectEl.innerHTML = '<option value="">Selecione seu banco</option>';
  for (const b of sorted) {
    const opt = document.createElement("option");
    opt.value = b.code;
    opt.textContent = `${b.code} — ${b.name}`;
    if (selectedCode && selectedCode === b.code) opt.selected = true;
    selectEl.appendChild(opt);
  }
};
